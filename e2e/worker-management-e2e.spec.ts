import { expect,test } from './fixtures';
import { authenticate } from './auth';
test('Attendance UI, wage register, payment and monthly summary reconcile', async ({ page, context }) => {
  await authenticate(context); const request = context.request;
  const names = [`Worker A ${Date.now()}`, `Worker B ${Date.now()}`];
  const workers = [];
  for (const [index, name] of names.entries()) workers.push(await (await request.post('/api/employees', { data: { name, wageType: 'DAILY', wageRate: index === 0 ? 600 : 500, status: 'ACTIVE' } })).json());
  await page.goto('/workers'); await expect(page.locator('main h1')).toContainText('Daily Attendance & Tracking');
  await page.locator('#attendance-date-picker').fill('2026-11-16');
  await page.locator(`#btn-present-${workers[0].id}`).click();
  await expect(page.locator(`#worker-wage-${workers[0].id}`)).toContainText('600');
  await page.locator(`#btn-halfday-${workers[1].id}`).click();
  await expect(page.locator(`#worker-wage-${workers[1].id}`)).toContainText('250');
  const register = await (await request.get(`/api/workers/wages?workerId=${workers[0].id}`)).json();
  expect(register.totalComputed).toBe(600);
  const paid = await request.post('/api/workers/wages', { data: { wageId: register.entries[0].id, paidAmount: 600, paidDate: '2026-11-16' } });
  expect((await paid.json()).paidStatus).toBe('PAID');
  expect((await (await request.get(`/api/workers/wages?workerId=${workers[0].id}`)).json()).totalBalance).toBe(0);
  await page.click('#tab-summary');
  await page.locator('#summary-month-select').selectOption('11');
  await page.locator('#summary-year-select').selectOption('2026');
  await expect(page.locator('#monthly-summary-table')).toContainText(names[0]);
  await expect(page.locator('#export-csv-btn')).toBeVisible();
});
